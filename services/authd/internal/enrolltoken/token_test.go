var update = flag.Bool("update", false, "rewrite testdata/vectors.json from the implementation")

const vectorsFile = "testdata/vectors.json"

type vectors struct {
	Comment string        `json:"comment"`
	Keys    string        `json:"keys"`
	Valid   []validLink   `json:"valid"`
	Invalid []invalidLink `json:"invalid"`
}

type validLink struct {
	Token string `json:"token"`
	EID   string `json:"eid"`
	Exp   int64  `json:"exp"`
	KID   int    `json:"kid"`
}

type invalidLink struct {
	Token string `json:"token"`
	Why   string `json:"why"`
}

func seqBytes(start, n int) []byte {
	b := make([]byte, n)
	for i := range b {
		b[i] = byte(start + i)
	}
	return b
}

func makeVectors() vectors {
	key2 := seqBytes(0x20, 32)
	key1 := seqBytes(0x01, 32)
	// First key is the signing key (kid=2); second key (kid=1) is accepted on verify.
	keysStr := "2:" + base64.StdEncoding.EncodeToString(key2) + ",1:" + base64.StdEncoding.EncodeToString(key1)
	ring2, _ := ParseNonEmptyRing("test", keysStr)
	ring1, _ := ParseNonEmptyRing("test", "1:"+base64.StdEncoding.EncodeToString(key1))

	eid1, _ := ParseUUID("019abcde-0123-789a-8bcd-ef0123456789")
	eid2, _ := ParseUUID("019abcde-ffff-7000-8000-000000000001")
	exp1 := int64(1795737600) // 2026-11-28T00:00:00Z
	exp2 := int64(1795738500)

	tok1, _ := SignLink(ring2, eid1, time.Unix(exp1, 0).UTC())
	tok2, _ := SignLink(ring1, eid2, time.Unix(exp2, 0).UTC())

	parts := strings.Split(tok1, ".")
	// Flip last byte of MAC to make invalid signature
	badMAC := parts[3][:len(parts[3])-1] + "A"
	if badMAC == parts[3] {
		badMAC = parts[3][:len(parts[3])-1] + "B"
	}
	// Non-canonical trailing bits in last base64url char (17 bytes = 136 bits, 23*6=138 bits -> 2 spare bits)
	nonCanonLast := parts[3][:len(parts[3])-1] + string(nextB64Char(parts[3][len(parts[3])-1]))

	return vectors{
		Comment: "Signed edge enrollment link tokens (services/authd/internal/enrolltoken). Generated by `go test -run TestVectors -update`; shared with apps/api/src/mail-devices/link-token.ts.",
		Keys:    keysStr,
		Valid: []validLink{
			{Token: tok1, EID: FormatUUID(eid1), Exp: exp1, KID: 2},
			{Token: tok2, EID: FormatUUID(eid2), Exp: exp2, KID: 1},
		},
		Invalid: []invalidLink{
			{"", "empty"},
			{"v2." + parts[1] + "." + parts[2] + "." + parts[3], "wrong version"},
			{"v1." + strings.ToUpper(parts[1]) + "." + parts[2] + "." + parts[3], "uppercase eid hex"},
			{"v1." + parts[1] + ".0" + parts[2] + "." + parts[3], "leading zero in exp"},
			{"v1." + parts[1] + ".0." + parts[3], "zero exp"},
			{"v1." + parts[1] + "." + parts[2] + "." + badMAC, "bad mac"},
			{"v1." + parts[1] + "." + parts[2] + "." + nonCanonLast, "non-canonical base64url trailing bits"},
			{"v1." + parts[1] + "." + parts[2] + "." + parts[3] + "=", "padded base64url"},
			{"v1." + parts[1] + "." + parts[2], "too few parts"},
			{"v1." + parts[1] + "." + parts[2] + "." + parts[3] + ".extra", "too many parts"},
		},
	}
}

func nextB64Char(c byte) byte {
	const alpha = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_"
	idx := strings.IndexByte(alpha, c)
	return alpha[(idx+1)%len(alpha)]
}

func TestVectors(t *testing.T) {
	want := makeVectors()
	if *update {
		if err := os.MkdirAll("testdata", 0o755); err != nil {
			t.Fatal(err)
		}
		b, err := json.MarshalIndent(want, "", "  ")
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(vectorsFile, append(b, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	raw, err := os.ReadFile(vectorsFile)
	if err != nil {
		t.Fatalf("%v (run with -update to write it)", err)
	}
	var got vectors
	if err := json.Unmarshal(raw, &got); err != nil {
		t.Fatal(err)
	}
	ring, err := ParseNonEmptyRing("ENROLL_EDGE_HMAC_KEY", got.Keys)
	if err != nil {
		t.Fatalf("ParseNonEmptyRing: %v", err)
	}
	for _, v := range got.Valid {
		if len(v.Token) != 68 {
			t.Errorf("token %q length = %d, want 68", v.Token, len(v.Token))
		}
		// Valid at exact expiry second.
		claims, err := VerifyLink(ring, v.Token, time.Unix(v.Exp, 0).UTC())
		if err != nil {
			t.Fatalf("VerifyLink(%q) at exp: %v", v.Token, err)
		}
		if claims.EnrollmentID != v.EID || int(claims.KeyID) != v.KID || claims.ExpiresAt.Unix() != v.Exp {
			t.Fatalf("claims = %+v, want %+v", claims, v)
		}
		// Expired one second after exp.
		if _, err := VerifyLink(ring, v.Token, time.Unix(v.Exp+1, 0).UTC()); !errors.Is(err, ErrExpired) {
			t.Fatalf("VerifyLink after exp: got %v, want ErrExpired", err)
		}
	}
	for _, inv := range got.Invalid {
		if _, err := VerifyLink(ring, inv.Token, time.Unix(1700000000, 0).UTC()); !errors.Is(err, ErrInvalid) {
			t.Errorf("VerifyLink(%q, %s) = %v, want ErrInvalid", inv.Token, inv.Why, err)
		}
	}
	if b, _ := json.MarshalIndent(want, "", "  "); !bytes.Equal(append(b, '\n'), raw) {
		t.Fatalf("%s is stale: run go test -run TestVectors -update", vectorsFile)
	}
}

func TestLinkRotationAndSignWithFirstKey(t *testing.T) {
	k1 := base64.StdEncoding.EncodeToString(seqBytes(0x10, 32))
	k2 := base64.StdEncoding.EncodeToString(seqBytes(0x30, 32))
	// Prepending k2 makes k2 the signing key while k1 still verifies.
	ring, err := ParseNonEmptyRing("ENROLL_EDGE_HMAC_KEY", "2:"+k2+",1:"+k1)
	if err != nil {
		t.Fatal(err)
	}
	oldOnly, err := ParseNonEmptyRing("ENROLL_EDGE_HMAC_KEY", "1:"+k1)
	if err != nil {
		t.Fatal(err)
	}
	eid, err := NewUUIDv7()
	if err != nil {
		t.Fatal(err)
	}
	now := time.Unix(1795737600, 0).UTC()
	exp := now.Add(15 * time.Minute)

	tokNew, err := SignLink(ring, eid, exp)
	if err != nil {
		t.Fatal(err)
	}
	cNew, err := VerifyLink(ring, tokNew, now)
	if err != nil || cNew.KeyID != 2 {
		t.Fatalf("signed with ring: claims=%+v err=%v, want kid=2", cNew, err)
	}
	if _, err := VerifyLink(oldOnly, tokNew, now); !errors.Is(err, ErrInvalid) {
		t.Fatalf("oldOnly accepted new key token: %v", err)
	}

	tokOld, err := SignLink(oldOnly, eid, exp)
	if err != nil {
		t.Fatal(err)
	}
	cOld, err := VerifyLink(ring, tokOld, now)
	if err != nil || cOld.KeyID != 1 {
		t.Fatalf("rotated ring rejected old key token: claims=%+v err=%v", cOld, err)
	}
}

func TestACMEPermitRoundTripAndRefusals(t *testing.T) {
	k1 := base64.StdEncoding.EncodeToString(seqBytes(0x40, 32))
	k2 := base64.StdEncoding.EncodeToString(seqBytes(0x60, 32))
	ring, err := ParseNonEmptyRing("ENROLLCTL_ACME_PERMIT_KEYS", "9:"+k2+",3:"+k1)
	if err != nil {
		t.Fatal(err)
	}
	otherRing, err := ParseNonEmptyRing("ENROLLCTL_ACME_PERMIT_KEYS", "9:"+k1)
	if err != nil {
		t.Fatal(err)
	}

	devID, err := NewUUIDv7()
	if err != nil {
		t.Fatal(err)
	}
	now := time.Unix(1795737600, 0).UTC()
	exp := now.Add(10 * time.Minute)

	tok, err := SignACMEPermit(ring, devID, exp)
	if err != nil {
		t.Fatal(err)
	}
	if len(tok) != ACMEPermitLen {
		t.Fatalf("ACME permit len = %d, want %d (must be <= 50 and <= 64 RFC 5280 OU limit)", len(tok), ACMEPermitLen)
	}
	claims, err := VerifyACMEPermit(ring, tok, now)
	if err != nil {
		t.Fatalf("VerifyACMEPermit: %v", err)
	}
	if claims.DeviceID != FormatUUID(devID) || claims.KeyID != 9 || claims.ExpiresAt.Unix() != exp.Unix() {
		t.Fatalf("claims = %+v", claims)
	}
	// Expired
	if _, err := VerifyACMEPermit(ring, tok, exp.Add(time.Second)); !errors.Is(err, ErrExpired) {
		t.Fatalf("expired permit: got %v, want ErrExpired", err)
	}
	// Wrong secret under same kid
	if _, err := VerifyACMEPermit(otherRing, tok, now); !errors.Is(err, ErrInvalid) {
		t.Fatalf("wrong key accepted: %v", err)
	}
	// Tampered byte
	raw, _ := base64.RawURLEncoding.DecodeString(tok)
	raw[5] ^= 0x01
	tampered := base64.RawURLEncoding.EncodeToString(raw)
	if _, err := VerifyACMEPermit(ring, tampered, now); !errors.Is(err, ErrInvalid) {
		t.Fatalf("tampered permit accepted: %v", err)
	}
	// Non-canonical base64url trailing bits
	nonCanon := tok[:len(tok)-1] + string(nextB64Char(tok[len(tok)-1]))
	if _, err := VerifyACMEPermit(ring, nonCanon, now); !errors.Is(err, ErrInvalid) {
		t.Fatalf("non-canonical permit accepted: %v", err)
	}
}

func TestNewUUIDv7Format(t *testing.T) {
	u, err := NewUUIDv7()
	if err != nil {
		t.Fatal(err)
	}
	if u[6]>>4 != 7 {
		t.Fatalf("version nibble = %d, want 7", u[6]>>4)
	}
	if u[8]>>6 != 2 {
		t.Fatalf("variant bits = %b, want 10", u[8]>>6)
	}
	s := FormatUUID(u)
	parsed, err := ParseUUID(s)
	if err != nil || parsed != u {
		t.Fatalf("ParseUUID(%q) = (%x, %v), want %x", s, parsed, err, u)
	}
	if got := hex.EncodeToString(u[:]); len(got) != 32 {
		t.Fatalf("hex len = %d", len(got))
	}
}

func FuzzVerifyTokens(f *testing.F) {
	v := makeVectors()
	ring, _ := ParseNonEmptyRing("fuzz", v.Keys)
	for _, g := range v.Valid {
		f.Add(g.Token)
	}
	for _, b := range v.Invalid {
		f.Add(b.Token)
	}
	devID, _ := NewUUIDv7()
	if p, err := SignACMEPermit(ring, devID, time.Unix(1795738000, 0)); err == nil {
		f.Add(p)
	}
	now := time.Unix(1795737600, 0).UTC()
	f.Fuzz(func(t *testing.T, s string) {
		if len(s) > 512 {
			return
		}
		_, _ = VerifyLink(ring, s, now)
		_, _ = VerifyACMEPermit(ring, s, now)
	})
}
