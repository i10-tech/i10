// The vectors are shared with the API's TypeScript minter, which must produce
// exactly these codes and hashes and refuse exactly these strings. They are
// written by this test (-update) from the Go implementation and checked against
// it on every run, so the file can only change together with the code.
var update = flag.Bool("update", false, "rewrite testdata/vectors.json from the implementation")

const vectorsFile = "testdata/vectors.json"

type vectors struct {
	Comment string `json:"comment"`
	// Label is the hash's domain-separation prefix, NUL included.
	Label string `json:"label"`
	// Keys is a MAIL_DEVICE_CODE_KEYS value the hashes are under.
	Keys    string    `json:"keys"`
	Valid   []valid   `json:"valid"`
	Invalid []invalid `json:"invalid"`
}

type valid struct {
	Code      string `json:"code"`
	ID        string `json:"id"`
	IDHex     string `json:"id_hex"`
	SecretHex string `json:"secret_hex"`
	KID       int    `json:"kid"`
	HashHex   string `json:"hash_hex"`
}

type invalid struct {
	Code string `json:"code"`
	Why  string `json:"why"`
	// Reserved is whether authd sends it to the device lane (where it is refused
	// as malformed) rather than to the password lane.
	Reserved bool `json:"reserved"`
}

func seq(start, n int) []byte {
	b := make([]byte, n)
	for i := range b {
		b[i] = byte(start + i)
	}
	return b
}

func makeVectors() vectors {
	key1, key7 := seq(0x00, 32), seq(0x80, 48)
	keys := "1:" + base64.StdEncoding.EncodeToString(key1) + ",7:" + base64.StdEncoding.EncodeToString(key7)
	ring := map[int][]byte{1: key1, 7: key7}

	mk := func(idHex, secretHex string, kid int) valid {
		var id [idLen]byte
		var secret [secretLen]byte
		_, _ = hex.Decode(id[:], []byte(idHex))
		_, _ = hex.Decode(secret[:], []byte(secretHex))
		c := New(id, secret)
		return valid{
			Code: c.String(), ID: c.ID(), IDHex: idHex, SecretHex: secretHex, KID: kid,
			HashHex: hex.EncodeToString(Hash(ring[kid], c)),
		}
	}
	v := vectors{
		Comment: "Mail device codes (services/authd/internal/devicecode). Generated by `go test -run TestVectors -update`; never edit by hand.",
		Label:   label,
		Keys:    keys,
		Valid: []valid{
			mk("019abcde0123789a8bcdef0123456789", hex.EncodeToString(seq(0x10, 32)), 1),
			mk("00000000000000000000000000000000", strings.Repeat("00", 32), 1),
			mk("ffffffffffffffffffffffffffffffff", strings.Repeat("ff", 32), 7),
			// The same secret under another id hashes differently: the id is in the hash.
			mk("019abcde0123789a8bcdef012345678a", hex.EncodeToString(seq(0x10, 32)), 1),
		},
	}
	good := v.Valid[0].Code
	idPart := good[len(Prefix) : len(Prefix)+idHexLen]
	secPart := good[len(Prefix)+idHexLen+1:]
	lastBitsSet := good[:len(good)-1] + string(nextB64(good[len(good)-1]))
	v.Invalid = []invalid{
		{"", "empty", false},
		{"right horse", "an ordinary password", false},
		{"i10dc", "the bare reserved prefix", true},
		{"i10dc1.", "the prefix alone", true},
		{good[:Len-1], "one character short", true},
		{good + "A", "one character long", true},
		{good + "\n", "a trailing LF", true},
		{good[:20] + "\r" + good[21:], "a CR in place of a hex digit", true},
		{Prefix + strings.ToUpper(idPart) + "." + secPart, "uppercase hex", true},
		{"i10dc2." + idPart + "." + secPart, "another version", true},
		{Prefix + idPart + ":" + secPart, "no dot between id and secret", true},
		{Prefix + idPart[:8] + "-" + idPart[8:12] + "-" + idPart[12:16] + "-" + idPart[16:20] + "-" + idPart[20:] + "." + secPart[:39], "a dashed UUID (still 83 characters)", true},
		{good[:Len-1] + "=", "padding", true},
		{good[:Len-2] + "+A", "the standard alphabet's +", true},
		{good[:Len-2] + "/A", "the standard alphabet's /", true},
		{lastBitsSet, "non-zero bits past the 32nd byte", true},
		{"i10dc1x" + good[len(Prefix):], "the prefix's dot replaced", true},
		{"I10DC1." + idPart + "." + secPart, "an uppercase prefix: not reserved, so an ordinary password", false},
		{" " + good[:Len-1], "a leading space: not reserved", false},
	}
	return v
}

// nextB64 is the URL-alphabet character after c.
func nextB64(c byte) byte {
	i := strings.IndexByte(urlAlphabet, c)
	return urlAlphabet[(i+1)%len(urlAlphabet)]
}

func TestVectors(t *testing.T) {
	want := makeVectors()
	if *update {
		b, err := json.MarshalIndent(want, "", "  ")
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(vectorsFile, append(b, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	raw, err := os.ReadFile(vectorsFile)
	if err != nil {
		t.Fatalf("%v (run with -update to write it)", err)
	}
	var got vectors
	if err := json.Unmarshal(raw, &got); err != nil {
		t.Fatal(err)
	}
	ring, err := ParseKeys(got.Keys)
	if err != nil || len(ring) != 2 {
		t.Fatalf("the vectors' keys: %v (%d keys)", err, len(ring))
	}
	if got.Label != label {
		t.Fatalf("label %q, want %q", got.Label, label)
	}
	for _, v := range got.Valid {
		c, err := Parse(v.Code)
		if err != nil {
			t.Fatalf("%s: %v", v.Code, err)
		}
		id := c.IDBytes()
		if hex.EncodeToString(id[:]) != v.IDHex || hex.EncodeToString(c.secret[:]) != v.SecretHex ||
			c.ID() != v.ID || c.String() != v.Code || DeviceID(v.Code) != v.ID {
			t.Fatalf("%s parsed as id %s secret %x", v.Code, c.ID(), c.secret)
		}
		if h := hex.EncodeToString(Hash(ring[byte(v.KID)], c)); h != v.HashHex {
			t.Fatalf("%s: hash %s, want %s", v.Code, h, v.HashHex)
		}
		stored, _ := hex.DecodeString(v.HashHex)
		if !Matches(ring[byte(v.KID)], c, stored) {
			t.Fatalf("%s does not match its own hash", v.Code)
		}
		other := ring[1]
		if v.KID == 1 {
			other = ring[7]
		}
		if Matches(other, c, stored) {
			t.Fatalf("%s matches under the wrong key", v.Code)
		}
	}
	for _, v := range got.Invalid {
		if _, err := Parse(v.Code); !errors.Is(err, ErrMalformed) {
			t.Errorf("%s (%q): Parse = %v, want ErrMalformed", v.Why, v.Code, err)
		}
		if HasReservedPrefix(v.Code) != v.Reserved {
			t.Errorf("%s (%q): reserved = %v, want %v", v.Why, v.Code, !v.Reserved, v.Reserved)
		}
		if DeviceID(v.Code) != "" {
			t.Errorf("%s (%q): has a device id", v.Why, v.Code)
		}
	}
	// The file is what the implementation writes, field for field.
	if b, _ := json.MarshalIndent(want, "", "  "); !bytes.Equal(append(b, '\n'), raw) {
		t.Fatalf("%s is stale: run go test -run TestVectors -update and review the diff", vectorsFile)
	}
}

func TestTheIDIsInTheHash(t *testing.T) {
	key := seq(0, 32)
	a, _ := Parse(makeVectors().Valid[0].Code)
	b, _ := Parse(makeVectors().Valid[3].Code)
	if a.secret != b.secret || a.id == b.id {
		t.Fatal("vectors 0 and 3 should share a secret under different ids")
	}
	if Matches(key, b, Hash(key, a)) {
		t.Fatal("a secret under another device's id matched")
	}
}

func TestKeysParse(t *testing.T) {
	if ks, err := ParseKeys(""); err != nil || len(ks) != 0 {
		t.Fatalf("an empty value = %v, %v; want an empty ring, which authd reads as no device sign-ins", ks, err)
	}
	for _, bad := range []string{"1", "1:" + base64.StdEncoding.EncodeToString(seq(0, 31)), "300:" + base64.StdEncoding.EncodeToString(seq(0, 32))} {
		if _, err := ParseKeys(bad); err == nil {
			t.Errorf("ParseKeys(%q) accepted", bad)
		}
	}
}

// FuzzParse: whatever Parse accepts has exactly one spelling (it re-encodes to
// the same string), is exactly Len bytes, and names the device DeviceID names.
func FuzzParse(f *testing.F) {
	for _, v := range makeVectors().Valid {
		f.Add(v.Code)
	}
	for _, v := range makeVectors().Invalid {
		f.Add(v.Code)
	}
	f.Fuzz(func(t *testing.T, s string) {
		c, err := Parse(s)
		if err != nil {
			if DeviceID(s) != "" {
				t.Fatalf("DeviceID(%q) = %q for a string Parse refuses", s, DeviceID(s))
			}
			return
		}
		if len(s) != Len || c.String() != s || DeviceID(s) != c.ID() || !HasReservedPrefix(s) {
			t.Fatalf("Parse(%q) accepted a second spelling of %q", s, c.String())
		}
	})
}
