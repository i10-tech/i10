/**
 * shadcn's DropdownMenu, with ONE deviation from upstream, recorded here
 * because copied components stay canonical unless the reason is written down.
 *
 * ⚠ EVERY ITEM IS `rounded-lg` WHERE UPSTREAM SAYS `rounded-sm`, AND THAT IS
 * ARITHMETIC RATHER THAN TASTE. A radius nested inside another has one correct
 * value: the outer radius minus the gap between them. The panel here is
 * `rounded-xl` with `p-1` — 18px and 4px — so an item's corners want 14px,
 * which is `rounded-lg`. Upstream's `rounded-sm` is 10px against our
 * `--radius`, and 10 inside 18 reads as a squarer shape floating in a rounder
 * one.
 *
 * ⚠ IT WENT UNNOTICED UNTIL A MENU HAD EXACTLY ONE ITEM IN IT. With a list,
 * the highlight is a band among other bands and nothing nearby shows the
 * mismatch; with one item the highlight is almost the whole panel, with the
 * panel's own corner four pixels outside its own — which is what the domains
 * row menu made visible.
 *
 * ⚠ AND THE SUBMENU PANEL IS `rounded-xl` TOO, so the same arithmetic holds
 * wherever an item lands. Upstream gives it `rounded-md`, which would leave
 * the same items sitting in a tighter corner.
 *
 * ⚠ AND ITEMS ARE `cursor-pointer` WHERE UPSTREAM SAYS `cursor-default`.
 * Upstream is following the native menu convention, where a menu is not a
 * page and the arrow never changes; this product is a web app whose every
 * other clickable thing shows a hand, and half the call sites in the console
 * were already adding `cursor-pointer` by hand to get it. One rule, in one
 * place, beats a rule that holds wherever somebody remembered it.
 *
 * ⚠ THE DEVIATION IS IN THE COMPONENT, NOT AT A CALL SITE. A radius fixed in
 * one menu is a radius that is wrong in the other eight, and the next person
 * to notice has no way of telling which spelling is the intended one.
 */

