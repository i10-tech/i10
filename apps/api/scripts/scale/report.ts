/**
 * The markdown report of a measurement run. Findings first, then every number.
 */
import type { DatabaseFacts, Measurement } from "./measure.js"

const cell = (v: unknown) =>
  String(v ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\n/g, " ")
const ms = (n: number) =>
  n >= 100 ? n.toFixed(0) : n >= 10 ? n.toFixed(1) : n.toFixed(2)
const table = (head: string[], rows: unknown[][]) =>
  [
    `| ${head.join(" | ")} |`,
    `| ${head.map(() => "---").join(" | ")} |`,
    ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`),
  ].join("\n")

const flagsOf = (m: Measurement) => [
  ...(m.analysis?.flags ?? []),
  ...m.nested.flatMap((n) =>
    n.analysis.flags.map((f) => `in a function called ${n.calls}x: ${f}`),
  ),
  ...m.nested
    .filter((n) => n.calls >= 10)
    .map(
      (n) =>
        `function statement run ${n.calls} times for one call: ${n.query.replace(/\s+/g, " ").slice(0, 80)}`,
    ),
]

export function renderReport(
  rows: Measurement[],
  facts: DatabaseFacts,
  o: { date: string },
): string {
  const out: string[] = []
  out.push(`# Database scale measurement, ${o.date}`, "")
  out.push(
    `Generated by \`bun scripts/scale/cli.ts measure\` (apps/api). Server: ${facts.server.version.split(",")[0]}, shared_buffers ${facts.server.sharedBuffers}, work_mem ${facts.server.workMem}, through PgBouncer in transaction mode. Times are client-side round trips through the pooler, warm cache, each in its own rolled-back transaction. See [README.md](README.md) for what the numbers mean.`,
    "",
  )

  const bugs = rows.filter((r) => r.expectation)
  out.push("## Wrong answers", "")
  out.push(
    bugs.length
      ? table(
          ["Entry", "Case", "What is wrong"],
          bugs.map((b) => [b.entry, b.case, b.expectation]),
        )
      : "None of the cases with an expectation failed.",
    "",
  )

  const flagged = rows
    .filter((r) => flagsOf(r).length > 0 || r.error)
    .sort((a, b) => b.p95 - a.p95)
  out.push(
    "## Flagged statements",
    "",
    "Sorted by p95. A flag is a plan property that grows with data; see the README for each rule.",
    "",
  )
  out.push(
    table(
      ["Entry", "Case", "#", "p50 ms", "p95 ms", "Flags / error"],
      flagged.map((r) => [
        r.entry,
        r.case,
        r.statement,
        ms(r.p50),
        ms(r.p95),
        [...flagsOf(r), r.error].filter(Boolean).join("; "),
      ]),
    ),
    "",
  )

  out.push(
    "## Plan stability across cases",
    "",
    "Distinct plan shapes per statement position across an entry's cases (huge, median, empty, missing). More than one is not wrong by itself; the shapes are in the plans file.",
    "",
  )
  const byEntry = new Map<string, Map<number, Set<string>>>()
  for (const r of rows) {
    if (!r.analysis) continue
    const m = byEntry.get(r.entry) ?? new Map<number, Set<string>>()
    byEntry.set(r.entry, m)
    const s = m.get(r.statement) ?? new Set<string>()
    m.set(r.statement, s)
    s.add(r.analysis.shape)
  }
  out.push(
    table(
      ["Entry", "Statements", "Distinct shapes per statement"],
      [...byEntry.entries()].map(([e, m]) => [
        e,
        m.size,
        [...m.entries()].map(([k, s]) => `#${k}: ${s.size}`).join(", "),
      ]),
    ),
    "",
  )

  out.push("## Every statement", "")
  out.push(
    table(
      [
        "Entry",
        "Case",
        "#",
        "Kind",
        "p50",
        "p95",
        "max",
        "runs",
        "rows",
        "buffers hit",
        "read",
        "Call site",
        "Runs",
      ],
      rows.map((r) => [
        r.entry,
        r.case,
        r.statement,
        r.kind,
        ms(r.p50),
        ms(r.p95),
        ms(r.max),
        r.runs,
        r.analysis?.rows ?? "",
        r.analysis?.sharedHit ?? "",
        r.analysis?.sharedRead ?? "",
        r.site,
        r.frequency,
      ]),
    ),
    "",
  )

  const nested = rows.flatMap((r) => r.nested.map((n) => ({ r, n })))
  out.push(
    "## Inside SQL and SECURITY DEFINER functions",
    "",
    "Statements run inside a function the registry statement called, planned by auto_explain in the same transaction.",
    "",
  )
  out.push(
    nested.length
      ? table(
          [
            "Entry",
            "Case",
            "Function statement",
            "Calls",
            "Exec ms (worst)",
            "Buffers",
            "Flags",
          ],
          nested.map(({ r, n }) => [
            r.entry,
            r.case,
            n.query.replace(/\s+/g, " ").slice(0, 120),
            n.calls,
            ms(n.analysis.executionMs),
            n.analysis.sharedHit + n.analysis.sharedRead,
            n.analysis.flags.join("; "),
          ]),
        )
      : "None.",
    "",
  )

  out.push(
    "## Table and index sizes",
    "",
    table(
      ["Relation", "Rows (estimate)", "Table", "Indexes", "Total"],
      facts.sizes.map((s) => [
        s.relation,
        s.rows.toLocaleString("en-US"),
        s.table,
        s.indexes,
        s.total,
      ]),
    ),
    "",
  )
  out.push(
    "## Indexes no measured query used",
    "",
    "`idx_scan = 0` after the run (statistics were reset at its start). The registry is the hot paths, not every query, so this is a list to check, not to drop. Unique indexes enforce constraints whether or not anything reads them.",
    "",
    table(
      ["Index", "Table", "Size", "Unique"],
      facts.unusedIndexes.map((u) => [
        u.index,
        u.table,
        u.size,
        u.unique ? "yes" : "no",
      ]),
    ),
    "",
  )
  out.push(
    "## Duplicate or redundant indexes",
    "",
    facts.duplicateIndexes.length
      ? table(
          ["Index", "Covered by", "Why"],
          facts.duplicateIndexes.map((d) => [d.index, d.covers, d.reason]),
        )
      : "None found.",
    "",
  )
  out.push(
    "## Top statements by total time (pg_stat_statements)",
    "",
    table(
      ["Statement", "Calls", "Total ms", "Mean ms", "Rows"],
      facts.topStatements.map((t) => [
        `\`${t.query.slice(0, 160).replace(/`/g, "'")}\``,
        t.calls,
        t.total_ms,
        t.mean_ms,
        t.rows,
      ]),
    ),
    "",
  )
  return out.join("\n")
}
