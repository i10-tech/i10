import type { Lang } from "./types.js"

/**
 * Per-language FILL data: names, month names, cities, currencies and the
 * boilerplate of a mail footer. Everything here is fictional or generic. The
 * given names and family names are common ones that are combined at random, so
 * a result can coincide with someone's name but never refers to a person.
 *
 * Dates and money are formatted by hand, not with Intl, so the output does not
 * change with the ICU version of whichever machine runs the generator.
 */

export interface Currency {
  code: string
  symbol: string
  /** Digits after the decimal separator. */
  decimals: 0 | 2
  symbolFirst: boolean
  space: boolean
  group: string
  decimal: string
  /** Multiplies the base price range, so a yen price is not 12 yen. */
  scale: number
}

export interface Footer {
  /** Why the person got this mail, for account mail. Has {product} and {email}. */
  received: string
  /** Why, for marketing mail. Has {product}. */
  subscribed: string
  automated: string
  help: string
  unsubscribe: string
  preferences: string
  /** Has {company} and {address}. */
  sentBy: string
}

export interface LangPack {
  dir: "ltr" | "rtl"
  given: string[]
  family: string[]
  /** Japanese and Chinese write the family name first. */
  familyFirst: boolean
  months: string[]
  cities: string[]
  currencies: Currency[]
  timeZones: string[]
  period: { month: string; year: string }
  footer: Footer
}

